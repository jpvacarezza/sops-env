import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { registryCtx } from '../../test/helpers/ctx.mjs';
import { main } from './materialize.mjs';

const VALUE = 'postgresql://user:materialize-secret@db/app';
const doc = { api: { DATABASE_URL: VALUE }, web: { API_URL: 'https://x' } };

describe('materialize', () => {
  let root;
  let ctx;
  let errors;
  const ignored = vi.fn(() => ({ status: 0 }));

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'sops-env-materialize-'));
    ctx = registryCtx({ api: ['DATABASE_URL'], web: ['API_URL'] }, { root });
    errors = [];
    vi.spyOn(console, 'error').mockImplementation((...args) =>
      errors.push(args.join(' ')),
    );
    vi.spyOn(console, 'log').mockImplementation(() => {});
    ignored.mockClear();
  });

  afterEach(() => vi.restoreAllMocks());

  const run = (argv, runGit = ignored) =>
    main(ctx, argv, { decrypt: () => doc, runGit });

  it('writes each app file with the generated header when git ignores it', () => {
    expect(run(['local', 'all'])).toBe(0);

    const text = readFileSync(join(root, 'apps/api/.env.local'), 'utf8');
    expect(text.split('\n')[0]).toMatch(
      /^# Generated by `sops-env materialize`/,
    );
    expect(text).toContain('DATABASE_URL=');
    expect(ignored).toHaveBeenCalledWith(ctx, [
      'check-ignore',
      '-q',
      '--',
      'apps/api/.env.local',
    ]);
    if (process.platform !== 'win32')
      expect(statSync(join(root, 'apps/api/.env.local')).mode & 0o777).toBe(
        0o600,
      );
  });

  it('regenerates a file it wrote before', () => {
    expect(run(['local', 'api'])).toBe(0);
    expect(run(['local', 'api'])).toBe(0);
  });

  it('regenerates a file a predecessor tool wrote', () => {
    const file = join(root, 'apps/api/.env.local');
    mkdirSync(join(root, 'apps/api'), { recursive: true });
    writeFileSync(
      file,
      '# Generated by `pnpm secrets:materialize` — do not edit.\nOLD="1"\n',
    );

    expect(run(['local', 'api'])).toBe(0);
    const text = readFileSync(file, 'utf8');
    expect(text.split('\n')[0]).toMatch(
      /^# Generated by `sops-env materialize`/,
    );
    expect(text).not.toContain('OLD=');
    expect(text).toContain('DATABASE_URL=');
  });

  it('refuses to overwrite a file it did not generate', () => {
    const file = join(root, 'apps/api/.env.local');
    mkdirSync(join(root, 'apps/api'), { recursive: true });
    writeFileSync(file, 'HAND_WRITTEN=1\n');

    expect(run(['local', 'all'])).toBe(1);
    expect(readFileSync(file, 'utf8')).toBe('HAND_WRITTEN=1\n');
    expect(errors.join('\n')).toMatch(
      /apps\/api\/\.env\.local exists and was not generated by sops-env/,
    );
    // Nothing is written when any target is refused.
    expect(existsSync(join(root, 'apps/web/.env.local'))).toBe(false);
  });

  it('refuses a target git does not ignore', () => {
    const runGit = vi.fn(() => ({ status: 1 }));

    expect(run(['local', 'api'], runGit)).toBe(1);
    expect(existsSync(join(root, 'apps/api/.env.local'))).toBe(false);
    expect(errors.join('\n')).toMatch(
      /apps\/api\/\.env\.local is not ignored by git/,
    );
  });

  it('fails closed when git cannot answer', () => {
    const runGit = vi.fn(() => ({ error: new Error('spawn git ENOENT') }));

    expect(run(['local', 'api'], runGit)).toBe(1);
    expect(existsSync(join(root, 'apps/api/.env.local'))).toBe(false);
    expect(errors.join('\n')).toMatch(/could not ask git/i);
  });

  it('never prints a value', () => {
    run(['local', 'all']);
    run(['local', 'all'], () => ({ status: 1 }));

    expect(errors.join('\n')).not.toContain(VALUE);
  });
});
