import { spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname } from 'node:path';

import { appEnvFilePath, secretsFilePath } from '../store/paths.mjs';
import { decryptSecretsFile } from '../store/decrypt.mjs';
import { formatEnvFile, isGeneratedEnvFile } from '../store/envfile.mjs';
import { parseTarget } from './args.mjs';
import { projectEnv } from '../store/project.mjs';

const usage = (ctx) =>
  `usage: sops-env materialize <${ctx.environments.join('|')}> <${ctx.apps.join('|')}|all>\n` +
  '   eg: sops-env materialize local all';

const defaultRunGit = (ctx, args) =>
  spawnSync('git', args, { encoding: 'utf8', cwd: ctx.root });

/**
 * Why `file` must not be written, or null. Fails closed: a git that cannot
 * answer is a refusal, the same rule as the store sweep in `check`.
 */
function refusal(ctx, file, runGit) {
  const relative = ctx.relative(file);
  if (existsSync(file) && !isGeneratedEnvFile(readFileSync(file, 'utf8')))
    return (
      `${relative} exists and was not generated by sops-env (its first line is not the ` +
      'generated header). Move it aside or delete it, then run materialize again.'
    );

  const result = runGit(ctx, ['check-ignore', '-q', '--', relative]);
  if (result.error || (result.status !== 0 && result.status !== 1))
    return (
      `Could not ask git whether ${relative} is ignored, so it might be committed. ` +
      `${result.error?.message ?? (result.stderr || '').trim()}`.trim()
    );
  if (result.status === 1)
    return `${relative} is not ignored by git; add it to .gitignore before writing plaintext there.`;
  return null;
}

/**
 * Write each app's dotenv file from the store.
 *
 * The escape hatch, not the main path: Next tooling and some editors want a
 * real file. The file is generated, gitignored and disposable — edit the
 * ciphertext and regenerate, never the other way round. So every target is
 * checked before anything is written: it must be gitignored, and an existing
 * file must carry the generated header.
 */
export function main(
  ctx,
  argv,
  { decrypt = decryptSecretsFile, runGit = defaultRunGit } = {},
) {
  const [environment, target] = argv;
  const apps = target === 'all' ? ctx.apps : [target];

  try {
    for (const app of apps) parseTarget(ctx, [environment, app], usage(ctx));
  } catch (error) {
    console.error(error.message);
    return 1;
  }

  const refusals = apps
    .map((app) => refusal(ctx, appEnvFilePath(ctx, app), runGit))
    .filter(Boolean);
  if (refusals.length > 0) {
    for (const message of refusals) console.error(message);
    return 1;
  }

  let doc;
  try {
    doc = decrypt(secretsFilePath(ctx, environment));
  } catch (error) {
    console.error(error.message);
    return 1;
  }

  for (const app of apps) {
    const env = projectEnv(ctx, doc, app);
    const file = appEnvFilePath(ctx, app);
    mkdirSync(dirname(file), { recursive: true });
    // 0600: the one file in the tree that holds plaintext secrets. `mode` only
    // applies on create, so a regenerated file is chmod-ed too.
    writeFileSync(file, formatEnvFile(env), { mode: 0o600 });
    try {
      chmodSync(file, 0o600);
    } catch (error) {
      if (process.platform !== 'win32') throw error;
    }
    console.log(
      `${ctx.relative(file)} — ${Object.keys(env).length} variables (${environment})`,
    );
  }

  return 0;
}
